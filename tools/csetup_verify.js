'use strict';
/*
C-SETUP VERIFICATION — Phase 3's gates, per the session plan section 5.3.

Method note. This script does NOT read a `c_setup_minutes` field off the task
dict, and deliberately so: model.py records one (line 287) but tools/model.js
does not, which is a mirror divergence reported separately. Instead it runs the
REAL loader three times under three different C-setup rules and reads the answer
off spread_minutes:

    flat8    = every C-carrying table gets exactly  8.0 min
    flat10   = every C-carrying table gets exactly 10.0 min   (the Phase 2 rule)
    seeded   = the shipped 8-10 range                          (the Phase 3 rule)

A table carries a C row iff flat10 - flat8 == 2.0 exactly. Its seeded setup is
then 8.0 + (seeded - flat8). That identifies the set and recovers every value
without trusting either language's bookkeeping, and it exercises the shipped
code path in all three cases rather than patching numbers after the fact.

Three jobs:
  1. Emit tools/csetup-fixture.json so test_csetup.py can assert Python agrees.
  2. Distribution sanity — near-uniform over 80..100 tenths, mean near 90.
  3. Table T-B — the 78-row sweep under flat10 vs seeded, same 199 dates, so the
     Type C change is attributable separately from the data change (T-A).

Run with: node --max-old-space-size=6144 tools/csetup_verify.js
*/
const fs = require('fs');
const path = require('path');

const A = require('./assumptions');
const M = require('./model');
const S = require('./scenarios');
const { sweepRow } = require('./build');

const REPO = path.join(__dirname, '..');
const DATA = path.join(REPO, A.DATA_FILE);
const SHIPPED_MIN = A.C_SETUP_MINUTES_MIN_TENTHS;
const SHIPPED_MAX = A.C_SETUP_MINUTES_MAX_TENTHS;

function loadUnder(minTenths, maxTenths, label) {
  A.C_SETUP_MINUTES_MIN_TENTHS = minTenths;
  A.C_SETUP_MINUTES_MAX_TENTHS = maxTenths;
  process.stdout.write(`  loading under ${label} ... `);
  const t = Date.now();
  const d = M.loadDays(DATA, false);
  console.log(`${((Date.now() - t) / 1000).toFixed(0)}s`);
  return d;
}

console.log('C-SETUP VERIFICATION — ' + A.DATA_FILE);
const flat8 = loadUnder(80, 80, 'flat 8.0');
const flat10 = loadUnder(100, 100, 'flat 10.0  (the Phase 2 rule)');
const seeded = loadUnder(SHIPPED_MIN, SHIPPED_MAX, `seeded ${SHIPPED_MIN / 10}-${SHIPPED_MAX / 10}  (shipped)`);

const dates = Object.keys(seeded).sort();
console.log(`\n${dates.length} plan dates`);

// ------------------------------------------- identify the C-carrying tables
const carriers = [];
let totalTasks = 0, shapeMismatch = 0;
for (const d of dates) {
  const a = flat8[d], b = flat10[d], c = seeded[d];
  if (a.length !== b.length || a.length !== c.length) { shapeMismatch++; continue; }
  for (let i = 0; i < c.length; i++) {
    totalTasks++;
    const delta = b[i].spread_minutes - a[i].spread_minutes;   // 2.0 iff it has a C row
    if (Math.abs(delta - 2.0) < 1e-9) {
      carriers.push({
        date: d, table: c[i].table_no,
        setup: 8.0 + (c[i].spread_minutes - a[i].spread_minutes),
      });
    } else if (Math.abs(delta) > 1e-9) {
      console.error(`  UNEXPECTED delta ${delta} on ${d} task ${i}`);
      process.exitCode = 1;
    }
  }
}
if (shapeMismatch) { console.error(`FATAL: ${shapeMismatch} dates changed task count between rules`); process.exit(1); }
console.log(`tasks reaching the model: ${totalTasks}`);
console.log(`tasks carrying a C setup: ${carriers.length} (${(100 * carriers.length / totalTasks).toFixed(1)}%)`);
console.log(`  profiled expectation was 6,271 B tables with a matching C row on (Plan Date, Table No)`);

// ------------------------------------------------------------- 1. fixture
function tableKey(v) {
  if (v === null || v === undefined) return '';
  if (typeof v === 'number') return String(v);
  return String(v).trim();
}
function fnv1a32(s) {
  let h = A.C_SETUP_HASH_OFFSET >>> 0;
  const bytes = Buffer.from(s, 'utf8');
  for (let i = 0; i < bytes.length; i++) {
    h = (h ^ bytes[i]) >>> 0;
    h = Math.imul(h, A.C_SETUP_HASH_PRIME) >>> 0;
  }
  return h >>> 0;
}
const steps = SHIPPED_MAX - SHIPPED_MIN + 1;
const fixture = [];
let fixtureBad = 0;
for (const r of carriers.slice(0, 40)) {
  const seed = `${r.date}|${tableKey(r.table)}`;
  const h = fnv1a32(seed);
  const tenths = SHIPPED_MIN + (h % steps);
  fixture.push({ seed, fnv32: h, tenths, minutes: tenths / 10 });
  if (Math.abs(tenths / 10 - r.setup) > 1e-9) {
    console.error(`  FIXTURE MISMATCH vs the model: ${seed} model=${r.setup} recomputed=${tenths / 10}`);
    fixtureBad++; process.exitCode = 1;
  }
}
fs.writeFileSync(path.join(__dirname, 'csetup-fixture.json'),
  JSON.stringify({
    note: 'Generated by tools/csetup_verify.js. Asserted by test_csetup.py, which CANNOT '
        + 'BE RUN on this machine (no Python). Run it first thing after Python is '
        + 'installed: it is the only check that Python and JS agree bit for bit.',
    seed_format: '{plan_date_iso}|{table_key}',
    min_tenths: SHIPPED_MIN, max_tenths: SHIPPED_MAX,
    hash_offset: A.C_SETUP_HASH_OFFSET, hash_prime: A.C_SETUP_HASH_PRIME,
    triples: fixture,
  }, null, 1) + '\n');
console.log(`\nwrote tools/csetup-fixture.json — ${fixture.length} triples, `
          + `${fixtureBad ? fixtureBad + ' MISMATCHED' : 'all verified against the shipped model'}`);

// -------------------------------------------------------- 2. distribution
const hist = new Map();
let sum = 0;
for (const r of carriers) {
  const t = Math.round(r.setup * 10);
  hist.set(t, (hist.get(t) || 0) + 1);
  sum += t;
}
const keys = [...hist.keys()].sort((a, b) => a - b);
const mean = sum / carriers.length / 10;
const ideal = carriers.length / steps;
let maxDev = 0;
for (const k of keys) maxDev = Math.max(maxDev, Math.abs(hist.get(k) - ideal) / ideal);
console.log(`\nDISTRIBUTION — ${keys.length} distinct values, expected ${steps} (${SHIPPED_MIN}..${SHIPPED_MAX} tenths)`);
console.log(`  mean ${mean.toFixed(4)} min  (ideal ${((SHIPPED_MIN + SHIPPED_MAX) / 20).toFixed(2)})`);
console.log(`  bucket counts ${Math.min(...keys.map(k => hist.get(k)))}..${Math.max(...keys.map(k => hist.get(k)))}, `
          + `ideal ${ideal.toFixed(1)}, worst deviation ${(100 * maxDev).toFixed(1)}%`);
console.log('  ' + keys.map(k => `${(k / 10).toFixed(1)}:${hist.get(k)}`).join('  '));

// ------------------------------------------------------------- 3. table T-B
function runSweep(dayset, label) {
  process.stdout.write(`  sweep under ${label} ... `);
  const t = Date.now();
  const out = {};
  for (const [key, sc] of S.sweepScenarios()) out[key] = sweepRow(M.runCarry(sc, dayset));
  console.log(`${((Date.now() - t) / 1000).toFixed(0)}s`);
  return out;
}
console.log('\nT-B — the 78-row sweep, flat 10.0 (Phase 2) against seeded 8-10 (Phase 3)');
A.C_SETUP_MINUTES_MIN_TENTHS = SHIPPED_MIN;
A.C_SETUP_MINUTES_MAX_TENTHS = SHIPPED_MAX;
const flatSweep = runSweep(flat10, 'flat 10.0');
const seededSweep = runSweep(seeded, 'seeded 8-10');

const FIELDS = ['utilization_pct', 'trolleys_per_day', 'peak', 'pieces_per_trolley',
  'avg_wait_hours', 'spreading_blocked_pct', 'cutting_blocked_pct', 'blocked_by_space',
  'compartment_fill_pct', 'garments_per_trolley_capacity'];
const present = FIELDS.filter(f => f in seededSweep[Object.keys(seededSweep)[0]]);
let rowsMoved = 0, fieldsMoved = 0;
const perField = {};
for (const k of Object.keys(seededSweep)) {
  let moved = false;
  for (const f of present) {
    if (flatSweep[k][f] !== seededSweep[k][f]) { moved = true; fieldsMoved++; perField[f] = (perField[f] || 0) + 1; }
  }
  if (moved) rowsMoved++;
}
const nRows = Object.keys(seededSweep).length;
console.log(`\n  sweep rows that moved: ${rowsMoved} of ${nRows}`);
console.log(`  field changes: ${fieldsMoved} of ${nRows * present.length}  (fields compared: ${present.join(', ')})`);
console.log('  by field: ' + (Object.keys(perField).length
  ? Object.entries(perField).map(([f, n]) => `${f} ${n}`).join(', ') : 'none'));

const HEAD = { '0|1|0|1': 'S0 Today', '1|1|0|1': 'S1 +same-MO', '1|2|0|1': 'S2 +2 batches', '1|2|60|1': 'S3 +WIP hold' };
console.log('\n  | scenario | util% | trolleys/day | pieces/trolley | spread blocked% |');
console.log('  |---|---|---|---|---|');
for (const [k, label] of Object.entries(HEAD)) {
  const a = flatSweep[k], b = seededSweep[k];
  if (!a || !b) { console.log(`  | ${label} | key ${k} not in sweep | | | |`); continue; }
  const f = (x, y) => (x === y ? `${x}` : `${x} -> ${y}`);
  console.log(`  | ${label} | ${f(a.utilization_pct, b.utilization_pct)} | `
    + `${f(a.trolleys_per_day, b.trolleys_per_day)} | `
    + `${f(a.pieces_per_trolley, b.pieces_per_trolley)} | `
    + `${f(a.spreading_blocked_pct, b.spreading_blocked_pct)} |`);
}
console.log('\nA moved number here is EXPECTED and is the point of the change: the mean setup');
console.log('falls 10.0 -> ~9.0 on the C-carrying tables, shifting spread_minutes, which');
console.log('shifts both sequencers\' sort order, which shifts adjacency — and adjacency is');
console.log('the binding constraint on trolleys (README Part 5).');
